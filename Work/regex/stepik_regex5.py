import re

# 1. Считываем весь поток ввода в одну строку
s = open(0).read()

# 2. Удаляем однострочные комментарии, занимающие всю строку вместе с переносом \n
s = re.sub(r"^ *#.*\n", r"", s, flags=re.M)

# 3. Удаляем хвостовые комментарии в конце строк кода
s = re.sub(r"#.*", r"", s)

# 4. Удаляем многострочные в тройных кавычках вместе с отступами и \n
s = re.sub(r' *"{3}.*?"{3}\n', r"", s, flags=re.S)

print(s)