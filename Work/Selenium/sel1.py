#Вход
from selenium import webdriver
import time

# 1. Запускаем браузер (в данном случае Google Chrome)
driver = webdriver.Chrome()

# 2. Переходим на любой сайт
driver.get('https://example.com')

# 3. Делаем паузу в 3 секунды, чтобы мы успели увидеть открытую вкладку глазами
time.sleep(3)

# 4. Обязательно закрываем браузер, чтобы он не висел в памяти компьютера
driver.quit()


# #(Решетка) — поиск по ID
#------------------------------------------------------------
#. (Точка) — поиск по классу
#Пример: div.quote или просто .quote
#Что делает: Ищет элементы, у которых в классе указано class="quote". Классы часто повторяются у разных элементов.
#--------------------------------------------------------------------
# Пробел (Потомок / Вложенность)
#Пример: div.tags-box a
#Что делает: Ищет все теги <a>, которые находятся внутри блока div с классом tags-box (на любой глубине вложенности).
#-------------------------------------------------------
#> (Знак больше / Прямой ребенок)
#Пример: ul > li
#Что делает: Ищет тег li, который лежит строго на уровень ниже (прямой потомок) тега ul.
#--------------------------------------------------------
# [] (Квадратные скобки / Атрибуты)
# Пример: input[type="submit"] или a[href="/login"]
#Что делает: Ищет элементы по любому произвольному атрибуту и его значению (type, href, name, placeholder и т.д.).